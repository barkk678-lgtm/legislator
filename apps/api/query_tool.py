_NUMBER_RE = re.compile(r"\d[\d,.]*")
# תחיליות עבריות נפוצות, כדי ש"בוועדת" ייחשב כאזכור של "ועדת"
_PREFIXES = "בכלמשהו"


def _normalize_for_support(text: str) -> str:
    """טקסט להשוואה: בלי ניקוד, בלי סימני פיסוק, ובלי תחיליות
    בתחילת מילה - כך ש"בוועדת הפנים" אצל המודל נחשב נתמך אם
    המשתמש כתב "ועדת הפנים"."""
    cleaned = re.sub(r"[^\w\s\"'׳״-]", " ", text or "")
    words = []
    for w in cleaned.split():
        words.append(w)
        # גם את הצורה בלי התחילית, כדי ששתיהן יימצאו
        if len(w) > 2 and w[0] in _PREFIXES:
            words.append(w[1:])
    return " " + " ".join(words) + " "


def _normalize_number(value: str) -> str:
    """"3,000" ו-"3000" הם אותו מספר. בלי זה המשתמש שכתב 3000 היה
    נחסם על 3,000 שהמודל ניסח."""
    return value.replace(",", "").rstrip(".")


def unsupported_source_claims(background: str, user_text: str) -> list[str]:
    """פרטים ברקע שאין להם זכר בדברי המשתמש - מקור מסוים, גוף או
    מספר. מחזירה רשימה של מה שנמצא, וריקה כשהכול נתמך.

    **פונקציה טהורה**, בלי רשת ובלי מודל, כדי שאפשר יהיה לבדוק
    אותה. ראו ההערה למעלה על מה שהיא במכוון **אינה** תופסת."""
    haystack = _normalize_for_support(user_text)
    found: list[str] = []
    for marker in _SOURCE_MARKERS:
        if marker in (background or "") and marker not in haystack:
            found.append(marker)
    # מספר שהומצא הוא פרט חדש לכל דבר ("על-פי נתוני 2024",
    # "ב-30% מהמקרים") - אלא אם המשתמש נקב בו בעצמו.
    user_numbers = {_normalize_number(n) for n in _NUMBER_RE.findall(user_text or "")}
    for number in _NUMBER_RE.findall(background or ""):
        if _normalize_number(number) not in user_numbers:
            found.append(number)
    return sorted(set(found))


class QueryDraftError(Exception):
    """שכבת אפליקציה - LLM לא זמין/נכשל, או המודל דיווח שאי אפשר לנסח."""


def _instructions(kind: QueryKind) -> str:
    limit = _WORD_LIMITS[kind]
    word_limit_instruction = (
        f"חייב להיות עד {limit} מילים בדיוק (מגבלת תקנון הכנסת, לא המלצה)."
        if limit
        else "אינו מוגבל במספר מילים (שאילתה ישירה)."
    )
    return _INSTRUCTIONS_TEMPLATE.format(kind=kind, word_limit_instruction=word_limit_instruction)


def _word_count(text: str) -> int:
    return len(text.split())


def body_word_count(body: str) -> int:
    """ש11 (26.9.2026): מה שנספר למגבלה - הגוף בלבד (רקע, "רצוני לשאול:",
    שאלות). הכותרת והנושא אינם בגוף מלכתחילה; מספור שאלות שהמודל הוסיף
    בעצמו ("1.") אינו מילה - הממשק והקובץ ממספרים בעצמם."""
    lines = [ln.strip() for ln in (body or "").split("\n")]
    return sum(_word_count(_LEADING_NUMBER_RE.sub("", ln)) for ln in lines)


_LEADING_NUMBER_RE = re.compile(r"^\s*(?:\d{1,2}|[א-י])\s*[.)\-–]\s+")

_FIT_RETRY = ("הגוף שניסחת כולל {count} מילים, והמגבלה היא {limit}. נסח מחדש כך "
              "שהגוף יהיה עד {limit} מילים - שלם ותקין, באותו נושא ובאותו פורמט. "
              "קצר קודם את הרקע.")


def draft_query(*, turns: list[dict], kind: QueryKind, minister: str, mk_name: str,
                fit_limit: bool = False) -> dict:
    """fit_limit (ש14): הבקשה באה מ"התכנס למגבלת המילים". אחרי הניסוח
    סופרים בקוד; אם עדיין חורג - ניסיון נוסף אחד עם הספירה בפועל. אם גם
    הוא חורג, within_limit=False חוזר והממשק אומר זאת למשתמש."""
    result = _draft_query_once(turns=turns, kind=kind, minister=minister, mk_name=mk_name)
    if fit_limit and not result["within_limit"]:
        retry = list(turns) + [
            {"role": "assistant", "content": f"{_SUBJECT_MARK} {result['subject']}\n{_BODY_MARK} {result['body']}"},
            {"role": "user", "content": _FIT_RETRY.format(count=result["word_count"], limit=result["word_limit"])},
        ]
        result = _draft_query_once(turns=retry, kind=kind, minister=minister, mk_name=mk_name)
        result["fit_attempts"] = 2
    return result


def _draft_query_once(*, turns: list[dict], kind: QueryKind, minister: str, mk_name: str) -> dict:
    """turns: השיחה עד כה, [{"role": "user"|"assistant", "content": ...}],
    כשהאחרון הוא ההודעה החדשה של המשתמש. מחזירה dict עם
    subject/body/word_count/within_limit - **לא** חוסמת אם חורג
    מהמגבלה (המשתמש רואה ועורך), רק מסמנת within_limit=False כדי
    שהממשק יתריע במפורש, לא ינחש/יחתוך מילים בשקט.

    **שיחה ולא מחרוזת מודבקת (ברק, ממצא 2026-09-22).** קודם כל
    הודעות המשתמש הודבקו ב-"\n" ונשלחו כתיאור אחד. התוצאה: המשתמש
    שאל שאלה לא תקינה, קיבל סירוב מוצדק, ואז שאל שאלה תקינה לגמרי -
    וקיבל שוב סירוב שמתייחס ל"חלק הראשון", כי הגוש עדיין הכיל אותו.
    גם בקשה מפורשת לענות רק על השנייה לא עזרה, מאותה סיבה בדיוק.
    בתורים נפרדים הסירוב הוא תור בהיסטוריה, לא חלק מהשאלה."""
    try:
        raw = draft_conversation(instructions=_instructions(kind), turns=turns, max_tokens=400)
    except (LLMConfigError, LLMRequestError) as e:
        raise QueryDraftError(f"שכבת ה-LLM לא זמינה: {e}") from None
    except ValueError as e:
        raise QueryDraftError(str(e)) from None

    if raw.startswith("לא ניתן לנסח שאילתה"):
        raise QueryDraftError(raw)

    subject_match = re.search(rf"{re.escape(_SUBJECT_MARK)}\s*(.+)", raw)
    body_match = re.search(rf"{re.escape(_BODY_MARK)}\s*(.+)", raw, re.DOTALL)
    if not subject_match or not body_match:
        raise QueryDraftError(f"תשובת ה-LLM לא בפורמט הצפוי (נושא:/גוף:): {raw!r}")

    subject = subject_match.group(1).strip()
    # **הנושא הוא שורה אחת; הגוף רב-שורתי** (רקע / "רצוני לשאול:" /
    # שאלות). חיתוך ברווח הלבן היה מאחד אותן לפסקה אחת - וזה בדיוק
    # מה שהשאילתה הגרועה שברק הראה עשתה.
    body, removed_addressee = _strip_addressee(body_match.group(1).strip())
    body = "\n".join(ln.strip() for ln in body.split("\n") if ln.strip())
    # **השומר רץ על פסקת הרקע בלבד** - השאלות עצמן אינן טוענות
    # עובדות, והמגבלה עליהן היא ניסוחית ולא ראייתית.
    background = body.split(_RETSONI)[0]
    user_text = "\n".join(t.get("content", "") for t in turns
                          if t.get("role") == "user")
    invented = unsupported_source_claims(background, user_text)
    if invented:
        # **קודם מנסים לנסח מחדש בלי הפרט, ורק אז חוסמים** (ברק,
        # 23.9.2026). חסימה היא המוצא האחרון: המשתמש מסר מידע תקין,
        # והמודל הוא שהוסיף עליו - אין סיבה שהוא ישלם על זה.
        retry_turns = list(turns) + [
            {"role": "assistant", "content": raw},
            {"role": "user", "content": _REWRITE_WITHOUT.format(
                items=", ".join(invented))},
        ]
        try:
            raw = draft_conversation(
                instructions=_instructions(kind), turns=retry_turns, max_tokens=400)
        except (LLMConfigError, LLMRequestError, ValueError):
            raw = ""
        subject_match = re.search(rf"{re.escape(_SUBJECT_MARK)}\s*(.+)", raw)
        body_match = re.search(rf"{re.escape(_BODY_MARK)}\s*(.+)", raw, re.DOTALL)
        if subject_match and body_match:
            subject = subject_match.group(1).strip()
            body, removed_addressee = _strip_addressee(body_match.group(1).strip())
            body = "\n".join(ln.strip() for ln in body.split("\n") if ln.strip())
            background = body.split(_RETSONI)[0]
            invented = unsupported_source_claims(background, user_text)
        if invented:
            raise QueryDraftError(
                "לא ניתן לנסח שאילתה: הניסוח כלל פרט שלא הופיע בדבריכם - "
                f"{', '.join(invented)}. ניסיתי לנסח מחדש בלעדיו וזה חזר. "
                "שאילתה מוגשת בשם חבר כנסת, ולכן כל פרט ברקע חייב להגיע "
                "ממה שמסרתם. אפשר להזכיר את הפרט הזה במפורש, או לבקש "
                "ניסוח כללי בלי מקור."
            )

    limit = _WORD_LIMITS[kind]
    wc = body_word_count(body)
    return {
        "kind": kind,
        "minister": minister,
        "mk_name": mk_name,
        "subject": subject,
        "body": body,
        "removed_addressee": removed_addressee,
        "word_count": wc,
        "word_limit": limit,
        "within_limit": limit is None or wc <= limit,
    }


