"""פורמט תאריך אחיד לכל מה שמוצג למשתמש (ב7, ברק 22.9.2026).

**הפורמט: 01.12.2026 - יום.חודש.שנה, בנקודות.** זה הפורמט הנהוג
בכנסת ובמסמכים רשמיים בעברית, והוא מה שמופיע בשאילתות האמיתיות
(`מועד אחרון למתן תשובה: 21/07/2026`).

**למה מודול ולא תיקון נקודתי:** הפיד מחזיר ISO (`2026-12-01T00:00:00`)
בשישה מקומות שונים - שאילתות, הצעות דומות, מראי מקום, מחקר, רשימת
החוקים, ועץ החוק - וכל אחד מהם חתך את המחרוזת ב-`[:10]` בנפרד.
תיקון של מקום אחד היה משאיר את החמישה האחרים, ועוד כאלה היו
נוספים. נקודה אחת שכולם עוברים דרכה היא מה שמונע את זה.

**מחרוזת שאינה תאריך מוחזרת כפי שהיא ולא נזרקת** - תאריך חלקי או
שדה ריק בפיד אינם סיבה להפיל בקשה, והצגתו כפי שהוא עדיפה על
היעלמותו.
"""

from __future__ import annotations

import re

_ISO_RE = re.compile(r"^(\d{4})-(\d{2})-(\d{2})")


def display_date(value: str | None) -> str | None:
    """ISO מהפיד -> 'DD.MM.YYYY'. None/ריק -> None."""
    if not value:
        return None
    match = _ISO_RE.match(str(value).strip())
    if not match:
        return str(value).strip() or None
    year, month, day = match.groups()
    return f"{day}.{month}.{year}"


__all__ = ["display_date"]
