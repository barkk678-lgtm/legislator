"""האם הצעת חוק **מתקנת חוק קיים** או **מציעה חוק חדש** (א6, ברק
22.9.2026).

**למה זה נדרש:** שתי בדיקות בוולידטור נכונות רק להצעות מתקנות -
בדיקה 4 (כותרת שוליים "{פעולה} סעיף {N}") ובדיקה 7 (שם ההצעה
בפורמט "חוק X (תיקון - תיאור)"). על הצעה לחוק חדש שתיהן נכשלות
תמיד, ושתי שגיאות שווא מוצגות למי שלא עשה דבר. מתוך 40 ההצעות
האמיתיות שנבדקו, **18 היו חוקים חדשים** (אומת עצמאית
ב-drafting-rules §5.8: 22 מתוך 40 מתקנות).

## שני מבחינים, לא אחד

CLAUDE.md: "מבחין יחיד הוא הנחה; שני מבחינים שמסכימים על כל הקורפוס
הם ראיה". כאן זה לא ניסוח יפה אלא הכרח - **נמדד שהכותרת לבדה אינה
מספיקה.**

**מבחין הכותרת** נבדק על 854 שמות ייחודיים מהכנסת ה-25 (נמשכו
מ-KNS_Bill). הוא תופס שתי צורות:
- `(תיקון - ...)`, `(תיקוני חקיקה)`, `(ביטול)` - סוגריים שפותחים
  בתיקון.
- `הצעת חוק **לתיקון** פקודת X (...)` - צורה שלמה שהמבחין הראשון
  שלי פספס לגמרי: התיקון מופיע לפני הסוגריים, והסוגריים מתארים את
  התוכן. **62 הצעות** סווגו בטעות כחוק חדש עד שהצורה הזו נוספה.

**ומה שנשאר שבור בכותרת:** משפחה שלמה כמו `הצעת חוק הרשויות
המקומיות (גמול השתתפות בישיבות והחזר הוצאות לחברי מועצה)` - שם של
חוק קיים עם סוגריים מתארים, בלי המילה "תיקון" בשום מקום. מהכותרת
לבדה **אי אפשר לדעת** אם היא מתקנת את החוק הקיים או מציעה חוק
עצמאי באותה משפחה. 30 שמות כאלה נמדדו.

**מבחין הגוף** הוא זה שמכריע בפועל: הוראת תיקון **תמיד** נפתחת
במילת יחס אל החוק המתוקן - "בחוק X", "בפקודת X", "בסעיף N לחוק
X". סעיף של חוק חדש הוא טקסט מהותי ולעולם אינו נפתח כך.

## וכשהם לא מסכימים - unknown, לא ניחוש

אם המבחינים חלוקים, הפונקציה מחזירה `"unknown"` ו**הבדיקות התלויות
מדווחות "לא נבדק" עם הסיבה** - לא רצות על ההנחה השגויה. זה אותו
עיקרון בדיוק כמו "unknown במקום ניחוש" (CLAUDE.md): תוצאה שגויה
שנראית בטוחה גרועה מאין-תוצאה.
"""

from __future__ import annotations

import re

# ── מבחין הכותרת ────────────────────────────────────────────────────
# סוגריים שפותחים בתיקון/ביטול. "מס'" נתפס דרך "תיקון" עצמו.
_PAREN_AMEND = re.compile(r"\(\s*(?:תיקון|תיקוני|ביטול)\b[^)]*\)")
# "הצעת חוק לתיקון פקודת X" / "חוק לתיקון חוק Y" - התיקון לפני הסוגריים.
_LETIKUN = re.compile(r"\bלתיקון\b")

# ── מבחין הגוף ──────────────────────────────────────────────────────
# הוראת תיקון נפתחת במילת יחס אל החוק/הפקודה המתוקנים. הרשימה אינה
# "מילות מפתח שנראות סבירות" אלא הצורות שהמנוע שלנו עצמו מייצר
# (packages/amend/engine._render_mutation) ושנצפו בהצעות אמיתיות.
_BODY_AMEND = re.compile(
    r"^\s*(?:ב|ל)(?:חוק|פקודת|פקודה|חוק־יסוד|חוק-יסוד)\b"
    r"|^\s*בסעיף\s+\S+\s+ל(?:חוק|פקודת)\b"
)
# **"בחוק זה" אינו הוראת תיקון - הוא סעיף ההגדרות של החוק עצמו.**
# נמדד (23.9.2026): הביטוי הזה לבדו סיווג ארבע הצעות לחוק חדש
# ("חופש הנחת תפילין", "הזכות לתקן", "אספקת החשמל", "הרשות הארצית
# למדידה") כהצעות מתקנות. הפניה עצמית היא ההפך הגמור מהפניה לחוק
# אחר, וזו ההבחנה המבנית - לא רשימת מילים.
_SELF_REFERENCE = re.compile(r"^\s*(?:ב|ל)(?:חוק|פקודה)\s+(?:זה|זו)\b")

# סעיפי סיום אינם מעידים על סוג ההצעה - הם מופיעים בשני הסוגים.
_CLOSING = re.compile(r"^\s*(?:תחילתו|תחילתה|תחילת|תחולה|הוראת מעבר|ביצוע ותקנות)\b")

Kind = str  # "amending" | "new" | "unknown"


def kind_from_title(title: str) -> Kind:
    """מהכותרת בלבד. מחזיר "amending" או "new" - **לעולם לא
    unknown**, כי כותרת בלי סימן תיקון נראית בדיוק כמו חוק חדש.
    חוסר הוודאות מתגלה רק מול מבחין הגוף."""
    t = (title or "").strip()
    if not t:
        return "new"
    return "amending" if (_PAREN_AMEND.search(t) or _LETIKUN.search(t)) else "new"


def kind_from_body(section_openings: list[str]) -> Kind:
    """מפתיחות הסעיפים ברמה העליונה. מחזיר unknown כשאין סעיפים
    בכלל - אין על מה לבסס, וזה לא "חוק חדש"."""
    openings = [s for s in (o.strip() for o in section_openings) if s]
    openings = [o for o in openings if not _CLOSING.search(o)]
    if not openings:
        return "unknown"
    amending = sum(1 for o in openings
                   if _BODY_AMEND.search(o) and not _SELF_REFERENCE.search(o))
    if amending == 0:
        return "new"
    # **רוב, ולא הוראה אחת.** נמדד (23.9.2026) שהצעה לחוק חדש מכילה
    # לעתים קרובות תיקון עקיף אחד בסופה ("בחוק הכשרות המשפטית...,
    # בתוספת, בסופה") - ולכן "די באחת" סיווג חוקים חדשים כמתקנים.
    # בהצעה מתקנת אמיתית, הוראות התיקון הן רוב הסעיפים המהותיים.
    return "amending" if amending * 2 >= len(openings) else "new"


def classify(title: str, section_openings: list[str]) -> tuple[Kind, str]:
    """(סוג, הסבר בעברית למשתמש). שני המבחינים; מחלוקת -> unknown."""
    by_title = kind_from_title(title)
    by_body = kind_from_body(section_openings)

    if by_body == "unknown":
        return by_title, (
            "לא נמצאו סעיפים במסמך, ולכן הסיווג נשען על שם ההצעה בלבד."
        )
    if by_title == by_body:
        return by_title, (
            "מתקנת חוק קיים - גם שם ההצעה וגם פתיחות הסעיפים מצביעים על כך."
            if by_title == "amending"
            else "הצעה לחוק חדש - אין בשם ההצעה סימן תיקון, ואף סעיף אינו "
                 "נפתח בהפניה לחוק קיים."
        )
    if by_body == "amending":
        # הגוף מכריע: סעיף שנפתח ב"בחוק X" הוא הוראת תיקון, גם אם
        # הכותרת אינה אומרת "תיקון" (משפחת "הרשויות המקומיות (...)").
        return "amending", (
            "מתקנת חוק קיים - שם ההצעה אינו אומר זאת, אבל סעיפים בה "
            "נפתחים בהפניה לחוק קיים."
        )
    return "unknown", (
        "לא ניתן לקבוע אם ההצעה מתקנת חוק קיים או מציעה חוק חדש: שם "
        "ההצעה כולל סימן תיקון, אבל אף סעיף אינו נפתח בהפניה לחוק קיים. "
        "בדיקות שתלויות בהבחנה הזו לא הורצו."
    )


def section_openings_from_bill(bill) -> list[str]:
    """פתיחות הסעיפים ברמה העליונה מתוך Bill. שורה ברמה העליונה היא
    depth == 0 עם מספר סעיף - בדיוק מה ש-render_bill.Line מסמן."""
    out: list[str] = []
    for line in getattr(bill, "lines", []) or []:
        if getattr(line, "depth", 0) == 0 and getattr(line, "number", ""):
            out.append(getattr(line, "text", "") or "")
    return out


__all__ = ["classify", "kind_from_body", "kind_from_title", "section_openings_from_bill"]
