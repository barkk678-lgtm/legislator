"""אילו סעיפים בחוק המתוקן ההצעה מתיימרת לתקן - בדיקה 1 על מסמך
שהועלה (ברק, 23.9.2026: "אם הן דורשות רק את החוק המתוקן, זה אותו
מנגנון של א6").

**למה מימוש נפרד ולא שימוש ב-_check_1 הקיימת:** הבדיקה הקיימת
משווה `Line.source_node_id` מול עץ ה"לפני". השדה הזה נוצר על ידי
המנוע שלנו ואינו קיים כלל במסמך חיצוני - ולכן הבדיקה הייתה
"עוברת" על כל מסמך שהועלה בלי לבדוק דבר. **זו אותה משפחה של
"לא נמצא" מול "לא הצלחתי לבדוק":** בדיקה שאין לה על מה לרוץ
ומדווחת "עבר" גרועה מבדיקה שלא רצה.

מה שכן אפשר לבדוק במסמך חיצוני הוא **מה שהבדיקה מתיימרת לבדוק
מלכתחילה** לפי הקטלוג: "מספרי הסעיפים בהוראות התיקון קיימים
בפועל בחוק המתוקן". את זה אפשר לאמת מול הקורפוס - אותו מנגנון
בדיוק כמו א6: שם החוק כתוב בהוראת התיקון עצמה, שולפים את החוק
מהמאגר, ובודקים.

## שני דברים שהקובץ הזה נזהר בהם, ושניהם נמדדו ולא הונחו

**1. הצעה מתקנת לא תמיד מתקנת חוק אחד.** מתוך 23 ההצעות המתקנות
בקורפוס הבדיקה, ארבע מתקנות שניים-שלושה חוקים (תיקון עקיף):
13569214 מתקנת את פקודת התעבורה **וגם** את חוק כביש אגרה ואת חוק
נתיבים מהירים. אם היינו אוספים את כל אזכורי הסעיפים ומשווים מול
חוק אחד, סעיפי החוקים האחרים היו מדווחים כ"לא קיימים" - כשל שווא.
לכן כל שורה נקשרת לחוק שהיא פונה אליו, ונאספים רק אזכורי **החוק
הראשי** (הראשון שההצעה מזכירה).

**2. סעיף שאינו הוראת תיקון אינו מפנה לחוק המתוקן בכלל.** "תחילתו
של סעיף 1" בסעיף התחילה מפנה לסעיף 1 של **ההצעה**, לא לסעיף 1 של
החוק. לכן שורה שאינה הוראת תיקון, ומה שמקונן תחתיה, אינם נאספים -
`current` מתאפס ל-None.
"""

from __future__ import annotations

import re

# ── זיהוי החוק שאליו פונה הוראת התיקון ──────────────────────────────
# "בחוק X, התש..–....", "בפקודת Y", "בחוק-יסוד: הכנסת"
_OPEN_LAW = re.compile(r"^\s*ב(?:חוק[־-]יסוד|חוק|פקודת|פקודה)\b")
# היכן נגמר שם החוק ומתחילה ההוראה. הפסיק לפני מילת ההוראה הכרחי:
# בלעדיו "בחוק הגבלת שימוש **במקום** לשם מניעת ביצוע עבירות" נחתך
# באמצע השם (נמדד על 13948408).
_NAME_END = re.compile(
    r"\s*\(להלן\b"
    r"|,\s*(?:אחרי|לפני|במקום|בסעיף|סעיף|בתוספת|בהגדרה|בהגדרות|בכותרת"
    r"|בפסקה|בפרט|בסופו|בסופה|בטל|בטלה|יבוא|בחלק|בפרק|בסימן|ברישה)\b"
    r"|\s+[–־-]\s"
    r"|\s+[–־-]\s*$"
)
# הפניה לחוק שכבר הוגדר: "בחוק העיקרי", "בסעיף 6ג1 לחוק העיקרי",
# "בפקודה". ממשיכה את החוק הראשי, לא פותחת חדש.
_MAIN_LAW_REF = re.compile(
    r"^\s*(?:ב|ל)?(?:חוק|פקודה)\s+(?:העיקרי|העיקרית)\b"
    r"|ל(?:חוק|פקודה)\s+(?:העיקרי|העיקרית)\b"
    r"|^\s*בפקודה\b"
)

# ── אילו אזכורי סעיף נאספים, ואילו לא ──────────────────────────────
#
# **הכלל: רק סעיף שההוראה מכוונת אליו.** הצורה "בסעיף N", "אחרי
# סעיף N", "לפני סעיף N", "במקום סעיף N", "סעיף N - בטל" היא הוראת
# תיקון שמצביעה על סעיף שחייב להתקיים בחוק. לעומת זאת "לפי סעיף N"
# או "סעיפים N או M" בתוך **הטקסט המוצע** מפנים פעמים רבות לסעיף
# שההצעה עצמה מוסיפה - הוא לא קיים בחוק, ובצדק. נמדד: 13569214
# מפנה בתוך הטקסט המוצע ל"לפי סעיף 85" - סעיף שההצעה עצמה יוצרת.
# **הוראת תיקון פותחת פסוקית; הפניה-אגב יושבת באמצעה.** "כאמור
# בסעיף 95ד" בתוך הפרק המוצע ב-13948370 מפנה לסעיף שההצעה עצמה
# יוצרת - ונספר ככשל עד שנוספה דרישת גבול-הפסוקית (תחילת שורה,
# פסיק, נקודה, סוגר או מקף). זה אינו סינון מילים אלא מבנה: מילת
# היחס של הוראת תיקון באה אחרי גבול, ולא אחרי מילה.
_TARGET_RE = re.compile(
    r"(?:^|[,;:.)\]]|\s[–־-])\s*(?:ב|אחרי\s+|לפני\s+|במקום\s+)"
    r"סעי(?:ף|פים)\s+([0-9][0-9א-ת׳'\"]*)",
    re.M)
# "סעיף 39 - בטל." - ביטול נוקב בסעיף בלי מילת יחס.
_REPEALED_RE = re.compile(
    r"(?:^|[,;:.)\]]|\s[–־-])\s*סעי(?:ף|פים)\s+([0-9][0-9א-ת׳'\"]*)\s*[–־-]\s*(?:בטל|בטלה|בטלים)")
# המשך רשימה: "בסעיפים 2, 3 ו-4" - כל מספר נוסף מיד אחרי הראשון.
_MORE_IN_LIST = re.compile(r"\s*(?:,|ו[־-]?)\s*([0-9][0-9א-ת׳'\"]*)")
# **אזכור שנוקב בחוק אחר אינו של החוק המתוקן.** "בסעיף 158טו1 לחוק
# התכנון והבנייה" בתוך הצעה שמתקנת את חוק מכשירי ההחייאה - שישה
# כשלי שווא ב-13821853 לפני התיקון הזה.
_OTHER_LAW_AFTER = re.compile(
    r"\s*(?:\([^)]*\)\s*)*ל(?:חוק|פקודת|פקודה)\s+(?!העיקרי|העיקרית)")
# מספר סעיף בכותרת שוליים: "תיקון סעיף 110". **"הוספת סעיף N"
# נוקבת בסעיף החדש שההצעה יוצרת** - ולכן אינה נאספת (13695183,
# 13948365, 13948392 נכשלו בדיוק על כך).
_HEADING_RE = re.compile(r"סעי(?:ף|פים)\s+([0-9][0-9א-ת׳'\"]*)")
_HEADING_ADDS = re.compile(r"\bהוספ")


def amended_law_name(text: str) -> str:
    """שם החוק שהוראת התיקון פותחת בו, או "" אם השורה אינה נפתחת
    בהפניה לחוק. מחזיר את השם כפי שהוא כתוב בהצעה, כולל השנה -
    כי זו הצורה שמתאימה ל-full_title בקורפוס."""
    if not _OPEN_LAW.match(text or ""):
        return ""
    body = text.lstrip()[1:]          # בלי ב' היחס
    match = _NAME_END.search(body)
    if match:
        body = body[: match.start()]
    return body.strip().rstrip(",").strip()


def _numbers_in(source: str, pattern: re.Pattern) -> list[str]:
    """כל המספרים שהתבנית תופסת בשורה, כולל המשך רשימה ("2ג ו-2ד"),
    ובלי אזכורים שנוקבים בחוק אחר."""
    out: list[str] = []
    for match in pattern.finditer(source):
        position = match.end()
        if _OTHER_LAW_AFTER.match(source, position):
            continue          # "בסעיף 158טו1 לחוק התכנון והבנייה" - חוק אחר
        out.append(match.group(1))
        while (more := _MORE_IN_LIST.match(source, position)) is not None:
            out.append(more.group(1))
            position = more.end()
    return out


def _citations_in_line(text: str, heading: str) -> list[str]:
    numbers: list[str] = []
    if heading and not _HEADING_ADDS.search(heading):
        numbers += _numbers_in(heading, _HEADING_RE)
    if text:
        numbers += _numbers_in(text, _TARGET_RE)
        numbers += _numbers_in(text, _REPEALED_RE)
    return numbers


def main_law_citations(bill) -> tuple[str, list[str]]:
    """(שם החוק הראשי שההצעה מתקנת, מספרי הסעיפים שהיא מפנה אליהם בו).

    שם ריק = לא נמצאה בהצעה הוראת תיקון שנוקבת בשם חוק. זה קורה גם
    בהצעה מתקנת לגיטימית (13948363 פותחת ב"בסעיף 6ג1 לחוק העיקרי",
    בלי לחזור על השם) - ואז הבדיקה מדווחת "לא נבדק", לא "עבר"."""
    main = ""
    current: str | None = None
    found: list[str] = []

    for line in getattr(bill, "lines", []) or []:
        text = getattr(line, "text", "") or ""
        heading = getattr(line, "side_heading", "") or ""
        is_section = getattr(line, "depth", 0) == 0 and bool(getattr(line, "number", ""))

        if is_section:
            # שורת סעיף פותחת הקשר חדש; מה שמקונן תחתיה יורש אותו.
            name = amended_law_name(text)
            if name:
                main = main or name
                current = name
            elif _MAIN_LAW_REF.search(text):
                current = main or None
            else:
                current = None   # סעיף שאינו הוראת תיקון - ראו הדוקסטרינג

        if current is None or current != main:
            continue

        for number in _citations_in_line(text, heading):
            number = number.strip(" \"'׳")
            if number and number not in found:
                found.append(number)

    return main, (found if main else [])


def missing_sections(cited: list[str], existing: set[str]) -> list[str]:
    """מה שההצעה מפנה אליו ואינו קיים בחוק. השוואה על המחרוזת
    כפי שהיא - `find_sections` מחזירה את אותה צורת מספר בדיוק."""
    return [n for n in cited if n not in existing]


