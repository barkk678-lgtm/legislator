"""התאמת מין בהחלפת גורם (הכרעה ג, ברק 26.9.2026) - **טבלאות סגורות בלבד.**

"שר הפנים יתקן" -> "הממשלה תתקן", לא "הממשלה יתקן". שתי טבלאות:
1. **מין הגורם** - לפי שם העצם הראשון בצירוף (בלי ה' הידיעה): "שר הפנים" - זכר,
   "ועדה ציבורית שימנה השר" - נקבה. צירוף שהמילה הראשונה שלו אינה בטבלה - מין
   לא ידוע, והרשומה לא מוחלפת בו.
2. **צמדי צורות** - פועל או תואר בזכר ובנקבה (יתקן/תתקן, רשאי/רשאית). מילה שאינה
   בטבלה - אין התאמה, ואז מחליפים רק בגורם מאותו מין.

המודל לא כותב כלום; אין כאן חוקי נטייה - רק מה שבטבלה.
"""

from __future__ import annotations

# ── מין הגורם: שם העצם הראשון בצירוף ─────────────────────────────────
_MASCULINE = {
    "שר", "ראש", "יועץ", "מנהל", "ממונה", "רשם", "מפקח", "נגיד", "מבקר", "סגן", "ועד", "וועד",
    "קוסם", "נציב", "יושב", "מנכ\"ל", "דמבלדור", "אפוטרופוס", "יועמ\"ש", "בית", "צוות",
}
_FEMININE = {
    "ממשלה", "מועצה", "מועצת", "רשות", "ועדה", "ועדת", "נציבות", "מליאה", "הנהלה", "הנהלת",
    "לשכה", "לשכת", "מזכירות", "חברה", "עירייה", "עיריית",
}

# ── צמדי צורות: זכר -> נקבה ─────────────────────────────────────────
_PAIRS = {
    "יתקן": "תתקן", "יקבע": "תקבע", "יפרסם": "תפרסם", "יורה": "תורה", "ימנה": "תמנה",
    "יגיש": "תגיש", "יודיע": "תודיע", "יאשר": "תאשר", "יתקין": "תתקין", "יחליט": "תחליט",
    "ידווח": "תדווח", "יביא": "תביא", "ייתן": "תיתן", "יעביר": "תעביר", "יפעל": "תפעל",
    "יבחן": "תבחן", "יכין": "תכין", "יקים": "תקים", "יחתום": "תחתום", "יאציל": "תאציל",
    "רשאי": "רשאית", "חייב": "חייבת", "מוסמך": "מוסמכת", "אחראי": "אחראית",
}
_BY_FORM = {**{m: ("m", f) for m, f in _PAIRS.items()}, **{f: ("f", m) for m, f in _PAIRS.items()}}


def gender(phrase: str) -> str | None:
    """"m" / "f" / None (לא בטבלה)."""
    words = phrase.split()
    if not words:
        return None
    head = words[0]
    if head.startswith("ה") and head[1:] in _MASCULINE | _FEMININE:
        head = head[1:]
    if head in _MASCULINE:
        return "m"
    if head in _FEMININE:
        return "f"
    return None


def inflect(word: str, to_gender: str) -> str | None:
    """הצורה של `word` במין `to_gender`, או None אם המילה אינה בטבלה."""
    entry = _BY_FORM.get(word)
    if entry is None:
        return None
    current, other = entry
    return word if current == to_gender else other


__all__ = ["gender", "inflect"]
