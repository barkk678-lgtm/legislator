"""התאמת מין בהחלפת גורם (הכרעה ג, ברק 26.9.2026) - **טבלאות סגורות בלבד.**

"שר הפנים יתקן" -> "הממשלה תתקן", לא "הממשלה יתקן". שתי טבלאות:
1. **מין הגורם** - לפי שם העצם הראשון בצירוף (בלי ה' הידיעה): "שר הפנים" - זכר,
   "ועדה ציבורית שימנה השר" - נקבה. צירוף שהמילה הראשונה שלו אינה בטבלה - מין
   לא ידוע, והרשומה לא מוחלפת בו.
2. **צמדי צורות** - פועל או תואר בזכר ובנקבה (יתקן/תתקן, רשאי/רשאית). מילה שאינה
   בטבלה - אין התאמה, ואז מחליפים רק בגורם מאותו מין.

המודל לא כותב כלום; אין כאן חוקי נטייה - רק מה שבטבלה.
"""

from __future__ import annotations

# ── מין הגורם: שם העצם הראשון בצירוף ─────────────────────────────────
_MASCULINE = {
    "שר", "ראש", "יועץ", "מנהל", "ממונה", "רשם", "מפקח", "נגיד", "מבקר", "סגן", "ועד", "וועד",
    "קוסם", "נציב", "יושב", "מנכ\"ל", "דמבלדור", "אפוטרופוס", "יועמ\"ש", "בית", "צוות",
}
_FEMININE = {
    "ממשלה", "מועצה", "מועצת", "רשות", "ועדה", "ועדת", "נציבות", "מליאה", "הנהלה", "הנהלת",
    "לשכה", "לשכת", "מזכירות", "חברה", "עירייה", "עיריית",
}

# ── טבלת הפעלים של חובה ורשות (אישורי הבנק §5) - סגורה ─────────────────
# שם הפועל -> (עתיד זכר, עתיד נקבה, עתיד רבים/רבות). 12 הקיימים + 14 החדשים.
VERBS = {
    "לתקן": ("יתקן", "תתקן", "יתקנו"), "לקבוע": ("יקבע", "תקבע", "יקבעו"),
    "למנות": ("ימנה", "תמנה", "ימנו"), "לפרסם": ("יפרסם", "תפרסם", "יפרסמו"),
    "להגיש": ("יגיש", "תגיש", "יגישו"), "להודיע": ("יודיע", "תודיע", "יודיעו"),
    "לאשר": ("יאשר", "תאשר", "יאשרו"), "להעביר": ("יעביר", "תעביר", "יעבירו"),
    "להתקין": ("יתקין", "תתקין", "יתקינו"), "לתת": ("ייתן", "תיתן", "ייתנו"),
    "להחליט": ("יחליט", "תחליט", "יחליטו"), "להביא": ("יביא", "תביא", "יביאו"),
    "להורות": ("יורה", "תורה", "יורו"), "להקים": ("יקים", "תקים", "יקימו"),
    "לבחון": ("יבחן", "תבחן", "יבחנו"), "לדווח": ("ידווח", "תדווח", "ידווחו"),
    "לבטל": ("יבטל", "תבטל", "יבטלו"), "להעניק": ("יעניק", "תעניק", "יעניקו"),
    "למסור": ("ימסור", "תמסור", "ימסרו"), "להזמין": ("יזמין", "תזמין", "יזמינו"),
    "להתיר": ("יתיר", "תתיר", "יתירו"), "להקצות": ("יקצה", "תקצה", "יקצו"),
    "להוציא": ("יוציא", "תוציא", "יוציאו"), "לשלם": ("ישלם", "תשלם", "ישלמו"),
    "לפעול": ("יפעל", "תפעל", "יפעלו"), "לחייב": ("יחייב", "תחייב", "יחייבו"),
}
# רשאי / חייב: זכר, נקבה, רבים, רבות
MODALS = {"רשאי": ("רשאי", "רשאית", "רשאים", "רשאיות"), "חייב": ("חייב", "חייבת", "חייבים", "חייבות")}
NUMBERS = ("m", "f", "pl", "fpl")
# §5 תיקון 2: שלילה לפני הפועל - הצמד לא מופעל ("אינו רשאי לתקן" לעולם לא "אינו יתקן")
NEGATIONS = ("אינו", "אינה", "אינם", "אינן", "לא", "אין")
_FUTURE = {forms[i]: (inf, n) for inf, forms in VERBS.items() for i, n in enumerate(("m", "f", "pl"))}


def verb_form(phrase: str) -> tuple[str, str, str] | None:
    """"יתקן" -> ("", "לתקן", "m"); "רשאית לתקן" -> ("רשאי", "לתקן", "f"); "חייבים לתקן" ->
    ("חייב", "לתקן", "pl"). צורה שאינה בטבלה - None. עתיד רבים ("יתקנו") - "pl" (רבים ורבות)."""
    if phrase in _FUTURE:
        inf, n = _FUTURE[phrase]
        return "", inf, n
    parts = phrase.split(" ")
    if len(parts) == 2 and parts[1] in VERBS:
        for modal, forms in MODALS.items():
            if parts[0] in forms:
                return modal, parts[1], NUMBERS[forms.index(parts[0])]
    return None


def conjugate(modal: str, inf: str, number: str) -> str | None:
    """הכיוון ההפוך של verb_form. עתיד ברבות ("fpl") - אותה צורה כמו ברבים."""
    if inf not in VERBS or number not in NUMBERS:
        return None
    if not modal:
        return VERBS[inf][min(NUMBERS.index(number), 2)]
    if modal not in MODALS:
        return None
    return f"{MODALS[modal][NUMBERS.index(number)]} {inf}"


def all_verb_forms() -> list[str]:
    """כל צורות הפועל בטבלה - עתיד, רשאי ל..., חייב ל... - בכל המינים והמספרים."""
    out = [f for forms in VERBS.values() for f in forms]
    out += [f"{m} {inf}" for forms in MODALS.values() for m in forms for inf in VERBS]
    return list(dict.fromkeys(out))


# ── צמדי צורות: זכר -> נקבה ─────────────────────────────────────────
_PAIRS = {**{forms[0]: forms[1] for forms in VERBS.values()}, 
    "יתקן": "תתקן", "יקבע": "תקבע", "יפרסם": "תפרסם", "יורה": "תורה", "ימנה": "תמנה",
    "יגיש": "תגיש", "יודיע": "תודיע", "יאשר": "תאשר", "יתקין": "תתקין", "יחליט": "תחליט",
    "ידווח": "תדווח", "יביא": "תביא", "ייתן": "תיתן", "יעביר": "תעביר", "יפעל": "תפעל",
    "יבחן": "תבחן", "יכין": "תכין", "יקים": "תקים", "יחתום": "תחתום", "יאציל": "תאציל",
    "רשאי": "רשאית", "חייב": "חייבת", "מוסמך": "מוסמכת", "אחראי": "אחראית",
}
_BY_FORM = {**{m: ("m", f) for m, f in _PAIRS.items()}, **{f: ("f", m) for m, f in _PAIRS.items()}}


def gender(phrase: str) -> str | None:
    """"m" / "f" / None (לא בטבלה)."""
    words = phrase.split()
    if not words:
        return None
    head = words[0]
    if head.startswith("ה") and head[1:] in _MASCULINE | _FEMININE:
        head = head[1:]
    if head in _MASCULINE:
        return "m"
    if head in _FEMININE:
        return "f"
    return None


def inflect(word: str, to_gender: str) -> str | None:
    """הצורה של `word` במין `to_gender`, או None אם המילה אינה בטבלה."""
    entry = _BY_FORM.get(word)
    if entry is None:
        return None
    current, other = entry
    return word if current == to_gender else other


