def get_manual_slug(wikitext_title: str) -> str | None:
    """מחזירה את ה-slug הגולמי (בלי תחילית) לחוק שיש לו רשומה
    במיפוי, או None אם אין. התחילית "manual-" מתווספת רק ב-
    law_id.resolve_law_id, לא כאן - ראו docstring המודול."""
