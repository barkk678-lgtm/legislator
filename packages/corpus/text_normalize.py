"""נרמול תווים בטקסט שנשלף מוויקיטקסט. ראו TASKS.md משימה 3.

נרמול הוא תווים בלבד - לא תיקון נוסח. שגיאות הקלדה בטקסט המקור
(למשל "ערב תתילתו" בחוק הקייטנות עצמו) חייבות לעבור ללא שינוי;
"לתקן" אותן היה באג חמור (חוק ברזל 1 - אין "נוסח בערך נכון").

שלושת ההחלפות (ראו docs/data-sources.md):
- מרכאות כפולות מסולסלות ” (U+201D) ו-“ (U+201C) -> " (U+0022)
- גרשיים עבריים ״ (U+05F4) -> " (U+0022)
- מקף עברי ־ (U+05BE, מפריד במילים מורכבות כמו "מבית־הספר") -> - (U+002D)

en-dash (U+2013) בשנים עבריות ("התש"ן–1990") אינו מטופל כאן - הוא כבר
מגיע נכון מהוויקיטקסט ואסור לגעת בו.
"""

_REPLACEMENTS = {
    "”": '"',  # ”
    "“": '"',  # “
    "״": '"',  # ״ גרשיים עבריים
    "־": "-",  # ־ מקף עברי
}

_TRANSLATION_TABLE = str.maketrans(_REPLACEMENTS)


def normalize_text(text: str) -> str:
    """מחליף תווי ציטוט/מקף מיוחדים בעברית בגרסתם הישרה. שומר על כל
    שאר התוכן, כולל שגיאות הקלדה, ללא שינוי."""
    return text.translate(_TRANSLATION_TABLE)
